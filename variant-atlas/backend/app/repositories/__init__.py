from __future__ import annotations
from typing import Protocol
from ..schemas import Workspace, Investigation
from ..run_schemas import RunSnapshot

class RepositoryError(Exception):
    pass

class Repository(Protocol):
    def workspace(self) -> Workspace: ...
    def seed(self, workspace: Workspace) -> None: ...
    def save(self, investigation: Investigation) -> None: ...
    def get(self, investigation_id: str) -> Investigation | None: ...
    def list(self) -> list[Investigation]: ...
    def save_run(self, run: RunSnapshot) -> None: ...
    def get_run(self, run_id: str) -> RunSnapshot | None: ...
    def list_runs(self) -> list[RunSnapshot]: ...
    def close(self) -> None: ...
